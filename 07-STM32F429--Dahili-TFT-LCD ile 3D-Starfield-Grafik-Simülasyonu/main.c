/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_I2C3_Init();
 //MX_LTDC_Init();
  //MX_SPI5_Init();
  //MX_DMA2D_Init();

  /* USER CODE BEGIN 2 */
  // CubeMX'in saatini kapattığı FMC yerine kartın kendi resmi BSP SDRAM başlatıcısını kullanıyoruz
  BSP_SDRAM_Init();

    // 2. Ekranı 240x320 ILI9341 profiliyle tam başlat
    BSP_LCD_Init();

    // 3. Katmanı ayarla
    BSP_LCD_LayerDefaultInit(LCD_BACKGROUND_LAYER, LCD_FRAME_BUFFER);
    BSP_LCD_SelectLayer(LCD_BACKGROUND_LAYER);
    BSP_LCD_DisplayOn();

    // 4. Ekranı tamamen siyah yap
    BSP_LCD_Clear(LCD_COLOR_BLACK);

    Init_Stars();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
      for (int i = 0; i < NUM_STARS; i++) {
          // Önceki yıldızı sil
          if (stars[i].prev_sx >= 4 && stars[i].prev_sx < (SCREEN_W - 4) &&
              stars[i].prev_sy >= 4 && stars[i].prev_sy < (SCREEN_H - 4)) {
              BSP_LCD_DrawPixel(stars[i].prev_sx, stars[i].prev_sy, LCD_COLOR_BLACK);
              BSP_LCD_DrawPixel(stars[i].prev_sx + 1, stars[i].prev_sy, LCD_COLOR_BLACK);
              BSP_LCD_DrawPixel(stars[i].prev_sx, stars[i].prev_sy + 1, LCD_COLOR_BLACK);
              BSP_LCD_DrawPixel(stars[i].prev_sx + 1, stars[i].prev_sy + 1, LCD_COLOR_BLACK);
          }

          // Yıldızı yaklaştır
          stars[i].z -= 2.0f;

          if (stars[i].z <= 10.0f) {
              stars[i].x = (float)((rand() % (SCREEN_W * 2)) - SCREEN_W);
              stars[i].y = (float)((rand() % (SCREEN_H * 2)) - SCREEN_H);
              stars[i].z = 240.0f;
              stars[i].prev_sx = -1;
              stars[i].prev_sy = -1;
              continue;
          }

          int sx = (int)((stars[i].x * 120.0f) / stars[i].z) + CX;
          int sy = (int)((stars[i].y * 120.0f) / stars[i].z) + CY;

          if (sx >= 4 && sx < (SCREEN_W - 4) && sy >= 4 && sy < (SCREEN_H - 4)) {
              uint32_t col = (stars[i].z < 80.0f) ? LCD_COLOR_WHITE : LCD_COLOR_CYAN;
              BSP_LCD_DrawPixel(sx, sy, col);
              BSP_LCD_DrawPixel(sx + 1, sy, col);
              BSP_LCD_DrawPixel(sx, sy + 1, col);
              BSP_LCD_DrawPixel(sx + 1, sy + 1, col);

              stars[i].prev_sx = sx;
              stars[i].prev_sy = sy;
          } else {
              stars[i].z = 0.0f;
          }
      }

      for (volatile int d = 0; d < 30000; d++);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

