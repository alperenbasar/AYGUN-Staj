/* USER CODE BEGIN PV */
#define NUM_STARS 70
#define SCREEN_W  240
#define SCREEN_H  320
#define CX        (SCREEN_W / 2)
#define CY        (SCREEN_H / 2)

typedef struct {
    float x, y, z;
    int prev_sx, prev_sy;
} Star;

Star stars[NUM_STARS];

void Init_Stars(void) {
    for (int i = 0; i < NUM_STARS; i++) {
        stars[i].x = (float)((rand() % (SCREEN_W * 2)) - SCREEN_W);
        stars[i].y = (float)((rand() % (SCREEN_H * 2)) - SCREEN_H);
        stars[i].z = (float)((rand() % 240) + 1);
        stars[i].prev_sx = -1;
        stars[i].prev_sy = -1;
    }
}
